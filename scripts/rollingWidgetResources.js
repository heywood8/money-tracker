#!/usr/bin/env node
/**
 * Writes the resources behind the exchange-rate widgets' rolling digits into
 * react-native-android-widget, for patches/react-native-android-widget@*.patch.
 *
 * The widget library draws a widget as one bitmap, which cannot move. The
 * patch takes a rate (a TextWidget given `rollingGroup`) out of the bitmap and
 * shows it in live views laid over it: one ViewFlipper per character, two
 * TextViews each, whose in/out animations the launcher runs. Only a widget
 * that rolls gets them: rn_widget_rolling_host.xml is the library's own
 * rn_widget.xml (day and night) with the slots added, so the other widgets,
 * and every widget below Android 12, inflate none. RemoteViews can only
 * target views by id, so every slot has ids of its own:
 *
 *   rn_rolling_g{group}_{rise|fall}           a group's container
 *   rn_rolling_g{group}_{rise|fall}_s{slot}   a character's flipper
 *   ..._a / ..._b                             its two TextViews
 *
 * A rise rolls the old digit down and brings the new one in from above; a
 * fall the other way. A flipper's animations are fixed in XML, so each
 * direction has flippers of its own.
 *
 * Usage, while patching the library (bun patch react-native-android-widget):
 *   node scripts/rollingWidgetResources.js
 * then commit the patch: bun patch --commit node_modules/react-native-android-widget
 */
const fs = require('fs');
const path = require('path');

// Two rates on the pair widget; a rate of up to 16 characters ("Rp16,300,000.00").
const GROUPS = 2;
const SLOTS = 16;
const DIRECTIONS = ['rise', 'fall'];
// One roll; RollingText.java steps a little slower so one ends before the next.
const ROLL_MS = 140;

const LIB = path.join(__dirname, '..', 'node_modules', 'react-native-android-widget', 'android', 'src', 'main');

const header = '<?xml version="1.0" encoding="utf-8"?>\n'
  + '<!-- Penny patch: generated by scripts/rollingWidgetResources.js; do not edit by hand. -->\n';

const anim = (from, to, comment) => `${header}<!-- ${comment} -->
<translate xmlns:android="http://schemas.android.com/apk/res/android"
    android:duration="${ROLL_MS}"
    android:fromYDelta="${from}"
    android:toYDelta="${to}"
    android:interpolator="@android:anim/decelerate_interpolator" />
`;

const ANIMS = {
  rn_rolling_rise_in: anim('-100%', '0%', 'A rise: the new digit comes in from above.'),
  rn_rolling_rise_out: anim('0%', '100%', 'A rise: the old digit rolls away below.'),
  rn_rolling_fall_in: anim('100%', '0%', 'A fall: the new digit comes in from below.'),
  rn_rolling_fall_out: anim('0%', '-100%', 'A fall: the old digit rolls away above.'),
};

// The face the library gives a bold TextWidget with no font family
// (Typeface.DEFAULT at weight 700), named outright so a launcher theme's text
// appearance cannot swap it. RollingText.slotProbe measures a TextView set up
// the same way, to put each slot's baseline on the drawn text's: keep the two
// in step.
const textView = (id) => `            <TextView
                android:id="@+id/${id}"
                android:layout_width="wrap_content"
                android:layout_height="wrap_content"
                android:fontFamily="sans-serif"
                android:includeFontPadding="true"
                android:letterSpacing="0"
                android:maxLines="1"
                android:textAllCaps="false"
                android:textStyle="bold" />`;

// Each flipper is placed by its margins (RemoteViews.setViewLayoutMargin) and
// clips its own children, which is what hides a digit rolling in or out. It
// animates its first flip too (animateFirstView, on by default): without it a
// freshly inflated widget's first roll in every slot would be a jump.
const slot = (group, dir, index) => {
  const id = `rn_rolling_g${group}_${dir}_s${index}`;
  return `        <ViewFlipper
            android:id="@+id/${id}"
            android:layout_width="wrap_content"
            android:layout_height="wrap_content"
            android:layout_gravity="top|left"
            android:inAnimation="@anim/rn_rolling_${dir}_in"
            android:outAnimation="@anim/rn_rolling_${dir}_out"
            android:visibility="gone">
${textView(`${id}_a`)}
${textView(`${id}_b`)}
        </ViewFlipper>`;
};

const container = (group, dir) => `    <FrameLayout
        android:id="@+id/rn_rolling_g${group}_${dir}"
        android:layout_width="match_parent"
        android:layout_height="match_parent"
        android:visibility="gone">
${Array.from({ length: SLOTS }, (_, index) => slot(group, dir, index)).join('\n')}
    </FrameLayout>`;

// Hidden from accessibility: the widget's label already says the rate, and
// TalkBack would otherwise read it a character at a time.
const layout = () => `${header}<FrameLayout xmlns:android="http://schemas.android.com/apk/res/android"
    android:layout_width="match_parent"
    android:layout_height="match_parent"
    android:importantForAccessibility="noHideDescendants">
${Array.from({ length: GROUPS }, (_, group) => DIRECTIONS.map((dir) => container(group, dir)).join('\n')).join('\n')}
</FrameLayout>
`;

const ids = (suffix) => `{
${Array.from({ length: GROUPS }, (_, group) => `        {
${DIRECTIONS.map((dir) => `            {${Array.from({ length: SLOTS }, (__, index) => `R.id.rn_rolling_g${group}_${dir}_s${index}${suffix}`).join(', ')}}`).join(',\n')}
        }`).join(',\n')}
    }`;

const java = () => `package com.reactnativeandroidwidget;

// Penny patch: generated by scripts/rollingWidgetResources.js; do not edit by hand.

/** The ids of res/layout/rn_widget_rolling.xml, by group, direction and slot. */
final class RollingIds {
    static final int GROUPS = ${GROUPS};
    static final int SLOTS = ${SLOTS};
    static final int RISE = 0;
    static final int FALL = 1;

    static final int[][] CONTAINERS = {
${Array.from({ length: GROUPS }, (_, group) => `        {${DIRECTIONS.map((dir) => `R.id.rn_rolling_g${group}_${dir}`).join(', ')}}`).join(',\n')}
    };

    static final int[][][] FLIPPERS = ${ids('')};

    static final int[][][] CHILD_A = ${ids('_a')};

    static final int[][][] CHILD_B = ${ids('_b')};

    private RollingIds() {
    }
}
`;

// The library's rn_widget.xml with the slots over its bitmaps, under the tap areas.
const CLICKABLE_ANCHOR = '    <FrameLayout\n        android:id="@+id/rn_widget_clickable_container"';
const host = (variant) => {
  const source = fs.readFileSync(path.join(LIB, 'res', variant, 'rn_widget.xml'), 'utf8').replace(/\r\n/g, '\n');
  if (!source.includes(CLICKABLE_ANCHOR) || source.includes('rn_widget_rolling')) {
    throw new Error(`res/${variant}/rn_widget.xml is not the library's own; restore it before generating`);
  }
  const include = '    <!-- Penny patch: the rolling slots, over the bitmaps and under the tap areas. -->\n'
    + '    <include layout="@layout/rn_widget_rolling" />\n\n';
  return header + source.replace(/^<\?xml[^>]*>\n/, '').replace(CLICKABLE_ANCHOR, include + CLICKABLE_ANCHOR);
};

const write = (relative, content) => {
  const file = path.join(LIB, relative);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  console.log(`wrote ${path.relative(process.cwd(), file)}`);
};

if (require.main === module) {
  Object.entries(ANIMS).forEach(([name, content]) => write(`res/anim/${name}.xml`, content));
  write('res/layout/rn_widget_rolling.xml', layout());
  write('res/layout/rn_widget_rolling_host.xml', host('layout'));
  write('res/layout-night/rn_widget_rolling_host.xml', host('layout-night'));
  write('java/com/reactnativeandroidwidget/RollingIds.java', java());
}

module.exports = { GROUPS, SLOTS, ROLL_MS };
